import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { app } from '../app';

interface RouteProtection {
  kind: 'auth' | 'permission' | 'role' | 'csrf' | 'rateLimit';
  value?: string;
}

interface HandlerLike {
  (...args: never[]): unknown;
  name?: string;
  stack?: LayerLike[];
  routeProtection?: RouteProtection;
}

interface LayerLike {
  handle?: HandlerLike;
  name?: string;
  regexp?: RegExp;
  keys?: Array<{ name: string }>;
  route?: {
    path: string | string[];
    methods: Record<string, boolean>;
    stack: LayerLike[];
  };
  stack?: LayerLike[];
}

interface ApplicationLike {
  _router?: { stack: LayerLike[] };
}

const routes: Array<{
  method: string;
  path: string;
  access: string;
  permission: string;
  csrf: string;
  rateLimit: string;
}> = [];

const applicationRouter = (app as unknown as ApplicationLike)._router;
if (!applicationRouter) throw new Error('Express application router is missing');
const applicationStack = applicationRouter.stack;

async function main(): Promise<void> {
  walk(applicationStack, '', []);
  routes.sort((left, right) =>
    `${left.path} ${left.method}`.localeCompare(
      `${right.path} ${right.method}`,
    ),
  );

  const markdown = [
    '# API Route Inventory',
    '',
    'Generated by `npm run routes:list` from the Express application stack.',
    '',
    '| Method | Path | Access | Permission or role | CSRF | Rate limited |',
    '|---|---|---|---|---|---|',
    ...routes.map(
      (route) =>
        `| ${route.method} | \`${route.path}\` | ${route.access} | ${route.permission} | ${route.csrf} | ${route.rateLimit} |`,
    ),
    '',
  ].join('\n');

  const outputPath = path.resolve(process.cwd(), 'docs', 'api-routes.md');
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, markdown, 'utf8');
  console.info(`Wrote ${routes.length} routes to ${outputPath}`);
}

void main().catch((error: unknown) => {
  console.error('Failed to generate API route inventory', error);
  process.exitCode = 1;
});

function walk(
  stack: LayerLike[],
  prefix: string,
  inherited: RouteProtection[],
): void {
  let active = [...inherited];
  for (const layer of stack) {
    if (layer.route) {
      const handlers = layer.route.stack
        .map(({ handle }) => handle)
        .filter((handler): handler is NonNullable<typeof handler> =>
          Boolean(handler),
        );
      const protections = [
        ...active,
        ...handlers.flatMap((handler) => classify(handler)),
      ];
      const pathValues = Array.isArray(layer.route.path)
        ? layer.route.path
        : [layer.route.path];
      for (const routePath of pathValues) {
        const fullPath = joinPath(prefix, routePath);
        const webhook = fullPath === '/api/webhooks/stripe';
        const auth = protections.find((protection) => protection.kind === 'auth');
        const permissions = protections
          .filter(
            (protection) =>
              protection.kind === 'permission' || protection.kind === 'role',
          )
          .map((protection) => `${protection.kind}: ${protection.value}`)
          .join(', ');
        const isCsrfGuarded =
          !webhook && protections.some(({ kind }) => kind === 'csrf');
        const isRateLimited =
          !webhook && protections.some(({ kind }) => kind === 'rateLimit');
        for (const [method, enabled] of Object.entries(layer.route.methods)) {
          if (!enabled) continue;
          routes.push({
            method: method.toUpperCase(),
            path: fullPath,
            access: auth?.value ?? 'public',
            permission: permissions || 'none',
            csrf: webhook
              ? 'exempt'
              : isCsrfGuarded
                ? 'guarded'
                : 'exempt',
            rateLimit: isRateLimited ? 'yes' : 'no',
          });
        }
      }
      continue;
    }

    const handle = layer.handle;
    if (handle?.stack) {
      walk(
        handle.stack,
      joinPath(prefix, fixedMountPath(layer.regexp, layer.keys)),
        active,
      );
      continue;
    }
    if (handle) active = [...active, ...classify(handle)];
  }
}

function classify(handler: NonNullable<LayerLike['handle']>): RouteProtection[] {
  const metadata = handler.routeProtection;
  if (metadata) return [metadata];
  return [];
}

function fixedMountPath(
  regexp: RegExp | undefined,
  keys: Array<{ name: string }> = [],
): string {
  if (!regexp) return '';
  let keyIndex = 0;
  const pathTemplate = regexp.source
    .replace(/\\\//g, '/')
    .replace(/^\^/, '')
    .replace(/\(\?:\/\(\[\^\/\]\+\?\)\)/g, () => {
      const key = keys[keyIndex++];
      return key ? `/:${key.name}` : '';
    })
    .replace(/\/?\(\?=\/\|\$\).*$/, '')
    .replace(/\/?\$$/, '')
    .replace(/\/\?$/, '');
  return pathTemplate.startsWith('/') ? pathTemplate : `/${pathTemplate}`;
}

function joinPath(prefix: string, routePath: string): string {
  const joined = `${prefix}/${routePath}`.replace(/\/+/g, '/');
  if (joined === '/') return '/';
  return joined.replace(/\/$/, '');
}
